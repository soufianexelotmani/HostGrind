@Injectable()
export class UiTranslationLoader implements TranslocoLoader {
  getTranslation(language: string) {
    const locale = language === 'fr' || language === 'ar' ? language : 'en';
    return of({ ui: UI_COPY[locale], auth: AUTH_COPY[locale] } as Translation);
  }
}

export type UiKey = keyof typeof UI_COPY.en;
export function navigationText(language: Language, key: UiKey): string {
  return UI_COPY[language][key];
}
